/**
 * `node scripts/capture-audio-corpus.mjs` — build a LOCAL audio corpus from audio you may
 * lawfully use, measure it, and print the abstention accounting.
 *
 * WHY THIS WRITES OUTSIDE THE REPOSITORY, WHICH IS THE WHOLE POINT OF THE SCRIPT.
 *
 * The other corpora in this project are captured and committed. This one is not, and the
 * refusal is recorded in `packages/detectors-audio/src/fixtures/corpus.ts` and enforced here:
 *
 *   - A HUMAN side has to be audio somebody can vouch for: known maker, known microphone,
 *     known room. Speech scraped off the internet is not that, and a corpus whose "human"
 *     label means "we found it somewhere" is the corpus the research literature keeps
 *     embarrassing itself with.
 *   - A SYNTHETIC side is easy to obtain and usually forbidden. The major text-to-speech
 *     vendors' terms bar using the Services or their Output to "train, fine-tune, develop,
 *     test, or improve" any model, and to "research and develop" a competing product.
 *     Fitting a detector's thresholds against their Output is squarely inside that sentence.
 *     Several of those vendors also ship a classifier, so the competing-product half is live.
 *
 * So the script requires you to state, per directory, WHERE the audio came from and WHETHER
 * you are permitted to use it this way. It refuses to run without both. What it writes goes
 * to `.corpus-cache/audio/`, which is gitignored, so a measurement of somebody's recording
 * cannot be committed by accident.
 *
 * USAGE
 *
 *   node scripts/capture-audio-corpus.mjs \
 *     --dir  ./my-recordings   --label human     --licence "recorded by me on a Zoom H5, my own room" \
 *     --dir  ./my-tts-output   --label generated --licence "generated by me; vendor terms permit this use"
 *
 *   --dir      a directory of audio files (not recursive)
 *   --label    human | generated | unknown, for that directory
 *   --licence  one sentence saying how you know the label and why you may use it here.
 *              Required. Under 40 characters is rejected: a corpus whose provenance line is
 *              "mine" is a corpus nobody can audit, including you in six months.
 *
 * It needs ffmpeg on PATH. Nothing here contacts a network and nothing is uploaded.
 */

import { readdir, mkdir, writeFile } from "node:fs/promises";
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildReport } from "@slop/core";
import { analyzeAudioArtifact, AUDIO_CONFIG, ingestAudio, listenToAudio } from "@slop/detectors-audio";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, ".corpus-cache", "audio");
const AUDIO_EXT = /\.(wav|mp3|m4a|aac|flac|ogg|opus|aiff?|caf)$/i;
const LABELS = new Set(["human", "generated", "unknown"]);

/** Parse repeated --dir/--label/--licence triples, in order. */
function parseArgs(argv) {
  const groups = [];
  let current = null;
  for (let i = 0; i < argv.length; i += 1) {
    const flag = argv[i];
    const value = argv[i + 1];
    if (flag === "--dir") {
      current = { dir: value, label: null, licence: null };
      groups.push(current);
      i += 1;
    } else if (flag === "--label" || flag === "--licence" || flag === "--license") {
      if (!current) fail(`${flag} appeared before any --dir.`);
      current[flag === "--label" ? "label" : "licence"] = value;
      i += 1;
    }
  }
  return groups;
}

function fail(message) {
  console.error(`\n  ${message}\n`);
  process.exit(1);
}

const groups = parseArgs(process.argv.slice(2));
if (groups.length === 0) {
  fail(
    "Nothing to capture. This script needs at least one --dir with a --label and a --licence.\n" +
      "  Read the header of this file first: there is a reason the audio corpus is not committed.",
  );
}
for (const g of groups) {
  if (!g.dir) fail("A --dir was given with no path.");
  if (!LABELS.has(g.label)) fail(`--dir ${g.dir} needs --label human|generated|unknown (got ${String(g.label)}).`);
  if (!g.licence || g.licence.trim().length < 40) {
    fail(
      `--dir ${g.dir} needs a --licence sentence of at least 40 characters saying how you know the label and why\n` +
        `  you may use this audio to tune a detector. A provenance line nobody can audit is not provenance.\n` +
        `  If the answer is "it came out of a text-to-speech API", check that vendor's terms before you continue:\n` +
        `  most of them forbid using their Output to develop, test or improve anything.`,
    );
  }
}

await mkdir(OUT_DIR, { recursive: true });

const index = [];
const reports = [];
let files = 0;

for (const group of groups) {
  const dir = path.resolve(group.dir);
  const entries = (await readdir(dir, { withFileTypes: true }).catch(() => [])).filter(
    (e) => e.isFile() && AUDIO_EXT.test(e.name),
  );
  if (entries.length === 0) fail(`No audio files found in ${dir}. A capture that reads nothing proves nothing.`);

  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    const stream = await listenToAudio(full, { enabled: true });
    if (stream.state === "tool_unavailable") fail(`${stream.note}`);

    const artifact = ingestAudio(new Uint8Array(readFileSync(full)), {
      locator: `local://${path.basename(dir)}/${entry.name}`,
      mediaType: null,
      stream,
    });
    const result = analyzeAudioArtifact(artifact, { kind: "file", path: full, mediaType: "audio/*" });
    const report = buildReport([result], { config: AUDIO_CONFIG });
    reports.push(report);
    files += 1;

    const id = `${path.basename(dir)}--${entry.name.replace(AUDIO_EXT, "")}`;
    index.push({
      id,
      label: group.label,
      source: `${path.basename(dir)}/${entry.name}`,
      provenance: group.licence.trim(),
      capturedAt: new Date().toISOString(),
      state: stream.state,
      status: report.status,
      score: report.score,
      evidenceKind: result.evidenceKind,
      abstention: report.abstention.map((a) => a.code),
      fired: report.receipt.lines.map((l) => l.ruleId),
      // The measurements themselves, so a threshold argument can be had against numbers.
      noiseFloorDb: stream.levels?.noiseFloorDb ?? null,
      noiseFloorIsDigitalZero: stream.levels?.noiseFloorIsDigitalZero ?? null,
      pauses: stream.silences.length,
      codec: stream.facts?.codec ?? null,
      sampleRateHz: stream.facts?.sampleRateHz ?? null,
      lossless: stream.facts?.lossless ?? null,
      laundered: artifact.laundering.laundered,
      launderingCodes: artifact.laundering.codes,
    });
    await writeFile(path.join(OUT_DIR, `${id}.artifact.json`), JSON.stringify(artifact, null, 2));
  }
}

await writeFile(path.join(OUT_DIR, "audio-corpus.index.json"), JSON.stringify(index, null, 2));

// ---- the accounting, which is the reason to run this ------------------------------------
const abstained = reports.filter((r) => r.status !== "assessed").length;
const byCode = {};
for (const r of reports) for (const a of r.abstention) byCode[a.code] = (byCode[a.code] ?? 0) + 1;
const pct = (n) => `${Math.round((n / Math.max(1, files)) * 1000) / 10}%`;

console.log(`\n  ${files} file(s) measured into ${path.relative(ROOT, OUT_DIR)} (gitignored).`);
console.log(`  scored     ${String(files - abstained).padStart(4)}  ${pct(files - abstained)}`);
console.log(`  ABSTAINED  ${String(abstained).padStart(4)}  ${pct(abstained)}`);
for (const [code, n] of Object.entries(byCode).sort((a, b) => b[1] - a[1])) {
  console.log(`    ${code.padEnd(26)} ${String(n).padStart(4)}  ${pct(n)}`);
}
console.log(
  `\n  This is an abstention rate over YOUR files. It is not a false-positive rate and it is not\n` +
    `  an accuracy figure: neither can be computed without a provenanced corpus on BOTH sides.\n` +
    `  Nothing written here is committed, and nothing derived from vendor output belongs in the\n` +
    `  shipped corpus, a baseline or a threshold.\n`,
);
