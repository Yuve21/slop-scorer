/**
 * Pull every string literal out of TypeScript source, ignoring comments AND regular expressions.
 *
 * The regex handling is not fussiness. The first draft of this scanner did not have it, and an
 * apostrophe inside a character class in `compose.ts` opened a phantom string that swallowed several
 * hundred characters of comment prose - which then reported a violation that did not exist, in text
 * that is not copy. A scanner that misreads its input is the same class of bug this repository
 * exists to catch, pointed the other way.
 */
function stringLiterals(source: string): string[] {
  const out: string[] = [];
  /** After one of these, a `/` opens a regular expression rather than dividing. */
  const REGEX_PRECEDERS = new Set(["(", ",", "=", ":", "[", "!", "&", "|", "?", "{", "}", ";", "+", "*", "\n", ""]);
  let lastSignificant = "";
  let i = 0;
  while (i < source.length) {
    const ch = source[i] as string;
    const next = source[i + 1];
    if (ch === "/" && next === "/") {
      while (i < source.length && source[i] !== "\n") i += 1;
      continue;
    }
    if (ch === "/" && next === "*") {
      i += 2;
      while (i < source.length && !(source[i] === "*" && source[i + 1] === "/")) i += 1;
      i += 2;
      continue;
    }
    if (ch === "/" && REGEX_PRECEDERS.has(lastSignificant)) {
      i += 1;
      let inClass = false;
      while (i < source.length) {
        const c = source[i];
        if (c === "\\") {
          i += 2;
          continue;
        }
        if (c === "[") inClass = true;
        else if (c === "]") inClass = false;
        else if (c === "\n") break;
        else if (c === "/" && !inClass) break;
        i += 1;
      }
      i += 1;
      lastSignificant = "/";
      continue;
    }
    if (ch === '"' || ch === "'" || ch === "`") {
      const quote = ch;
      i += 1;
      let buf = "";
      while (i < source.length && source[i] !== quote) {
        if (source[i] === "\\") {
          i += 2;
          buf += " ";
          continue;
        }
        // Template holes are not copy. Replace with a space so the words either side do not fuse.
        if (quote === "`" && source[i] === "$" && source[i + 1] === "{") {
          let depth = 1;
          i += 2;
          while (i < source.length && depth > 0) {
            if (source[i] === "{") depth += 1;
            if (source[i] === "}") depth -= 1;
            i += 1;
          }
          buf += " ";
          continue;
        }
        buf += source[i];
        i += 1;
      }
      i += 1;
      out.push(buf);
      lastSignificant = '"';
      continue;
    }
    if (!/\s/.test(ch)) lastSignificant = ch;
    else if (ch === "\n") lastSignificant = "\n";
    i += 1;
  }
  return out;
}

/**
 * A lowercase identifier-shaped literal is a code, not copy: `"produced"`, `"safety_refusal"`,
 * `"image/png"`. Every reader-facing string in this package is sentence-cased or upper-cased, so
 * this filter cannot hide one - and it is narrow enough that `"ai-generated"` in a sentence, or
 * `"AI-generated"` alone, still goes through the guard.
 */
const isCode = (literal: string): boolean => /^[a-z0-9_./:-]*$/.test(literal);

async function sourceFiles(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await sourceFiles(full)));
    else if (entry.name.endsWith(".ts")) out.push(full);
  }
  return out;
}

/**
 * `claims.ts` is the one exclusion, and it is unavoidable: it has to WRITE every phrase it bans, so
 * scanning it would make this test permanently red. Pinning the exclusion list at length one is what
 * stops it from quietly becoming the place inconvenient copy goes to live.
 */
const EXCLUDED = ["claims.ts"];

describe("every string literal in the source", () => {
  it("scans a non-empty set of files and literals, and sees the copy it is supposed to see", async () => {
    const files = await sourceFiles(srcDir);
    expect(files.length).toBeGreaterThan(12);
    const literals = (await Promise.all(files.map((f) => readFile(f, "utf8")))).flatMap(stringLiterals);
    expect(literals.length).toBeGreaterThan(200);
    // Sentinels: if the tokenizer breaks, these disappear and everything below goes vacuously green.
    expect(literals).toContain(DISCLAIMER_HEADING);
    expect(literals.some((l) => l.includes("cheap for us to remake"))).toBe(true);
    expect(literals.some((l) => l.includes("affirmative, conscious"))).toBe(true);
  });

  it("keeps the exclusion list at exactly one file", () => {
    expect(EXCLUDED).toEqual(["claims.ts"]);
  });

  it("contains no forbidden claim", async () => {
    const files = (await sourceFiles(srcDir)).filter((f) => !EXCLUDED.includes(path.basename(f)));
    const violations: string[] = [];
    for (const file of files) {
      for (const literal of stringLiterals(await readFile(file, "utf8"))) {
        if (isCode(literal)) continue;
        for (const v of findClaimViolations(literal)) {
          violations.push(`${path.relative(srcDir, file)}: [${v.kind}] ${v.detail}\n    in: ${v.sentence}`);
        }
      }
    }
    expect(violations, violations.join("\n")).toEqual([]);
  });
});
