export interface BorderBox extends Box {
  readonly found: boolean;
}

/**
 * Recover the outermost bordered rectangle from the pixels.
 *
 * A column that is ink for most of the image height, and a row that is ink for most of its width,
 * are the card border. Reading it back rather than trusting the layout is what makes "the band is
 * inside the same border as both panels" a statement about the finished image.
 */
export function findEnclosingBorder(r: Raster): BorderBox {
  // Columns first. A border column is ink for nearly the full image height; a dark panel plate is
  // ink for a third of it at most, so nothing in the artwork can be mistaken for the frame.
  const inkyColumns: number[] = [];
  for (let x = 0; x < r.width; x += 1) {
    let n = 0;
    for (let y = 0; y < r.height; y += 1) if (luma(getPixel(r, x, y)) < 128) n += 1;
    if (n >= r.height * 0.8) inkyColumns.push(x);
  }
  if (inkyColumns.length < 2) return { x: 0, y: 0, w: 0, h: 0, found: false };
  const x0 = inkyColumns[0] as number;
  const x1 = inkyColumns[inkyColumns.length - 1] as number;

  // Rows are then measured only ACROSS the frame, and have to be all but solid. Two very dark
  // plates side by side can cover most of a row; they cannot cover the gutter and both inner pads
  // as well, so they cannot pass at this threshold and drag the top of the frame down over the
  // panel labels - which would turn a correct figure into a false failure.
  const span = x1 - x0 + 1;
  const inkyRows: number[] = [];
  for (let y = 0; y < r.height; y += 1) {
    let n = 0;
    for (let x = x0; x <= x1; x += 1) if (luma(getPixel(r, x, y)) < 128) n += 1;
    if (n >= span * 0.98) inkyRows.push(y);
  }
  if (inkyRows.length < 2) return { x: 0, y: 0, w: 0, h: 0, found: false };
  const y0 = inkyRows[0] as number;
  const y1 = inkyRows[inkyRows.length - 1] as number;
  return { x: x0, y: y0, w: x1 - x0 + 1, h: y1 - y0 + 1, found: true };
}

export interface ProminenceReport {
  readonly ok: boolean;
  readonly problems: readonly string[];
  /** Measured from the pixels. Null when the label line could not be read back at all. */
  readonly labelHeightPx: number | null;
  readonly disclaimerHeightPx: number | null;
  readonly recoveredDisclaimer: string;
  readonly lines: readonly OcrLine[];
}

const norm = (s: string): string => s.toUpperCase().replace(/\s+/g, " ").trim();

/**
 * THE SHIP-BLOCKING CHECK.
 *
 * `design/SELF-AUDIT.md` risk 3 asks for exactly this and calls it the only test in the repository
 * whose failure is a legal exposure rather than a bug: render, OCR, assert the disclaimer is
 * present at >= the panel-label pixel height. Four things are asserted, and each one corresponds to
 * a real way a share card loses its disclaimer:
 *
 *   - the panel labels are readable at all (otherwise the comparison has no denominator);
 *   - the ENTIRE disclaimer body is recoverable, not merely its first line (catches clipping);
 *   - every disclaimer line's measured glyph height is >= the label's (catches shrinking);
 *   - the disclaimer sits inside the same border as both panel labels (catches a band moved
 *     outside the card, and catches a crop that removed it).
 */
export function checkDisclaimerProminence(r: Raster): ProminenceReport {
  const lines = ocrLines(r);
  const problems: string[] = [];

  const labelLine = lines.find((l) => l.text.includes(SUBMITTED_LABEL) && l.text.includes(RECREATION_LABEL));
  if (labelLine === undefined) {
    problems.push(
      `neither panel label was readable in the finished pixels (looked for ${JSON.stringify(SUBMITTED_LABEL)} and ${JSON.stringify(RECREATION_LABEL)} on one line)`,
    );
  }

  const headingLine = lines.find((l) => norm(l.text) === norm(DISCLAIMER_HEADING));
  if (headingLine === undefined) problems.push(`the disclaimer heading ${JSON.stringify(DISCLAIMER_HEADING)} is not in the pixels`);

  const bodyLines = headingLine === undefined ? [] : lines.filter((l) => l.top > headingLine.top);
  const recovered = norm(bodyLines.map((l) => l.text).join(" "));
  const wanted = norm(DISCLAIMER_BODY.replace(/[^A-Za-z0-9 .,:\-/()$?!'%+=*]/g, "?"));
  if (!recovered.includes(wanted)) {
    problems.push(
      `the disclaimer body was not recovered in full from the pixels. wanted: ${JSON.stringify(wanted)} / read: ${JSON.stringify(recovered)}`,
    );
  }

  const band = headingLine === undefined ? [] : [headingLine, ...bodyLines];
  const disclaimerHeightPx = band.length === 0 ? null : Math.min(...band.map((l) => l.glyphHeightPx));
  const labelHeightPx = labelLine?.glyphHeightPx ?? null;

  if (labelHeightPx !== null && disclaimerHeightPx !== null && disclaimerHeightPx < labelHeightPx) {
    problems.push(
      `the disclaimer renders at ${disclaimerHeightPx}px where the panel labels render at ${labelHeightPx}px. The band must never be smaller than the labels it qualifies.`,
    );
  }

  const border = findEnclosingBorder(r);
  if (!border.found) {
    problems.push("no enclosing border was found, so the disclaimer cannot be shown to share a frame with the panels");
  } else {
    const inside = (l: OcrLine): boolean =>
      l.top >= border.y && l.top + l.glyphHeightPx <= border.y + border.h && l.left >= border.x;
    if (labelLine !== undefined && !inside(labelLine)) problems.push("the panel labels fall outside the enclosing border");
    for (const l of band) {
      if (!inside(l)) {
        problems.push(`a disclaimer line falls outside the enclosing border: ${JSON.stringify(l.text)}`);
        break;
      }
    }
  }

  return {
    ok: problems.length === 0,
    problems,
    labelHeightPx,
    disclaimerHeightPx,
    recoveredDisclaimer: recovered,
    lines,
  };
}

export interface SymmetryReport {
  readonly ok: boolean;
  readonly problems: readonly string[];
}

/**
 * The panels must be interchangeable as objects.
 *
 * `design/SURFACES.md` A.5: "If the recreation is styled as the answer and the original as the
 * evidence, the layout has made an accusation the copy then has to walk back." Equal plate size,
 * equal label row, and equal distance from each outer edge.
 */
export function checkPanelSymmetry(layout: FigureLayout): SymmetryReport {
  const problems: string[] = [];
  const [a, b] = layout.plates;
  if (a.w !== b.w || a.h !== b.h) problems.push(`plates differ in size: ${a.w}x${a.h} vs ${b.w}x${b.h}`);
  if (a.y !== b.y) problems.push(`plates differ in vertical position: ${a.y} vs ${b.y}`);
  const leftInset = a.x - layout.card.x;
  const rightInset = layout.card.x + layout.card.w - (b.x + b.w);
  if (leftInset !== rightInset) problems.push(`plates are not mirrored: ${leftInset}px from the left edge, ${rightInset}px from the right`);
  const [la, lb] = layout.labelBoxes;
  if (la.y !== lb.y || la.h !== lb.h) problems.push("the two panel labels are not on the same row at the same size");
  const [ma, mb] = layout.metaBoxes;
  if (ma.y !== mb.y || ma.h !== mb.h) problems.push("the two panel meta lines are not on the same row at the same size");
  if (layout.disclaimerHeightPx < layout.labelHeightPx) {
    problems.push(`the layout allocates ${layout.disclaimerHeightPx}px to the disclaimer and ${layout.labelHeightPx}px to the labels`);
  }
  return { ok: problems.length === 0, problems };
}
